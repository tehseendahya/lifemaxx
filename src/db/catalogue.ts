/**
 * Every alias the seed will write for an entry, including the two it derives:
 * the slug with spaces, and the lowercased name. Shared with the test so the
 * uniqueness check covers exactly what reaches the unique index.
 */
export function aliasesFor(entry: CatalogueEntry): string[] {
  return [...new Set(
    [entry.slug.replace(/-/g, " "), entry.name, ...entry.aliases]
      .map((a) => a.toLowerCase().trim()),
  )];
}
